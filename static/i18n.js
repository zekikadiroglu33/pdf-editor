// t(key, fallbackEn, vars) - looks up key in the Turkish table when the
// page's locale is Turkish, otherwise returns fallbackEn untouched (the
// call site always supplies the real English text, so this never needs an
// "en" table of its own). vars does simple {name} substitution for both
// branches, since server-supplied bits (filenames, counts) never have a
// translation.
function pdferT(key, fallbackEn, vars) {
  let s = (window.pdferLocale === 'tr' && PDFER_TR[key] !== undefined) ? PDFER_TR[key] : fallbackEn;
  if (vars) {
    for (const k in vars) s = s.split('{' + k + '}').join(vars[k]);
  }
  return s;
}
window.pdferT = pdferT;

if (window.pdferLocale === 'tr') {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (PDFER_TR[key] !== undefined) el.textContent = PDFER_TR[key];
  });
  document.querySelectorAll('[data-i18n-html]').forEach(el => {
    const key = el.getAttribute('data-i18n-html');
    if (PDFER_TR[key] !== undefined) el.innerHTML = PDFER_TR[key];
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.getAttribute('data-i18n-placeholder');
    if (PDFER_TR[key] !== undefined) el.placeholder = PDFER_TR[key];
  });
  document.querySelectorAll('[data-i18n-aria-label]').forEach(el => {
    const key = el.getAttribute('data-i18n-aria-label');
    if (PDFER_TR[key] !== undefined) el.setAttribute('aria-label', PDFER_TR[key]);
  });
}
